export const TREASURE_BITMAPS = Object.fromEntries(TREASURES.map((t) => [t.id, bitmap(t.rows)])) as Record<
  TreasureId,
  Bitmap
>;

export function treasureName(id: TreasureId): string {
  return TREASURES.find((t) => t.id === id)?.name ?? id;
}

/** "an acorn", "a crown". */
export function withArticle(name: string): string {
  return `${/^[aeiou]/i.test(name) ? "an" : "a"} ${name}`;
}
